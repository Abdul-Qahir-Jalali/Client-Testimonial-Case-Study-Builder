_ATTRS = 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'


def inner(name: str) -> str:
    """The icon's shapes without the <svg> wrapper."""
    return ICONS[name]


def svg(name: str, size: int = 16, cls: str = "") -> str:
    """Inline Lucide icon. Inherits the surrounding text colour (stroke=currentColor)."""
    klass = f' class="lucide {cls}"' if cls else ' class="lucide"'
    return (f'<svg xmlns="http://www.w3.org/2000/svg"{klass} width="{size}" height="{size}" viewBox="0 0 24 24" '
            f'{_ATTRS} aria-hidden="true">{ICONS[name]}</svg>')


def mask_url(name: str) -> str:
    body = (f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='#000' stroke-width='2' "
            f"stroke-linecap='round' stroke-linejoin='round'>{ICONS[name].replace('currentColor', '#000')}</svg>")
    return f'url("data:image/svg+xml,{quote(body)}")'


def widget_icons_css(rules: list[tuple[str, str]]) -> str:
    """CSS that draws a Lucide icon before the label text of native Streamlit widgets.

    Each rule is (selector_for_the_label_paragraph, icon_name). The icon is a CSS mask filled with
    currentColor, so it follows hover / selected / disabled colours like the text does.
    """
    css = []
    for selector, name in rules:
        css.append(f'{selector}::before{{content:"";flex:none;width:17px;height:17px;background-color:currentColor;'
                   f'-webkit-mask:{mask_url(name)} center/contain no-repeat;mask:{mask_url(name)} center/contain no-repeat}}')
        css.append(f'{selector}{{display:inline-flex !important;align-items:center;gap:8px}}')
    return "\n".join(css)
