def _node_dirs() -> list[str]:
    dirs = [str(Path(p).parent) for p in (shutil.which("node"), shutil.which("npx")) if p]
    for guess in (r"C:\Program Files\nodejs", "/usr/local/bin", "/opt/homebrew/bin"):
        if (Path(guess) / ("node.exe" if os.name == "nt" else "node")).exists():
            dirs.append(guess)
    return list(dict.fromkeys(dirs))


def _ffmpeg_dirs() -> list[str]:
    """Folders holding both ffmpeg and ffprobe (HyperFrames needs both; imageio-ffmpeg ships only ffmpeg)."""
    exe = ".exe" if os.name == "nt" else ""
    found = [str(Path(p).parent) for p in (shutil.which("ffmpeg"), shutil.which("ffprobe")) if p]
    winget = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "WinGet" / "Packages"
    if winget.exists():
        found += [str(p.parent) for p in winget.glob(f"Gyan.FFmpeg*/**/bin/ffprobe{exe}")]
    found += [g for g in ("/usr/local/bin", "/opt/homebrew/bin", "/usr/bin") if (Path(g) / f"ffprobe{exe}").exists()]
    return [d for d in dict.fromkeys(found) if (Path(d) / f"ffmpeg{exe}").exists() and (Path(d) / f"ffprobe{exe}").exists()]


def _tool_path() -> str:
    return os.pathsep.join(_node_dirs() + _ffmpeg_dirs() + [os.environ.get("PATH", "")])


def _npx() -> str | None:
    return shutil.which("npx", path=_tool_path())


def missing_tool() -> str | None:
    """Plain-language description of what is missing for this video style, or None when it can run."""
    if not _npx():
        return "Node.js 22 or newer (nodejs.org)"
    if not _ffmpeg_dirs():
        return "FFmpeg with ffprobe (Windows: winget install Gyan.FFmpeg; macOS: brew install ffmpeg)"
    return None


def available() -> bool:
    return missing_tool() is None


def _gsap_tag() -> str:
    """Use a cached local copy of GSAP when we can get one (renders then work offline); else the CDN."""
    try:
        if not GSAP_CACHE.exists():
            GSAP_CACHE.parent.mkdir(parents=True, exist_ok=True)
            with urllib.request.urlopen(GSAP_URL, timeout=20) as resp:
                GSAP_CACHE.write_bytes(resp.read())
        return "assets/gsap.min.js"
    except Exception:
        return GSAP_URL


