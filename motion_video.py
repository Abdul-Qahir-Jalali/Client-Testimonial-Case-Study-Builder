def _mux_audio(silent: Path, audio: list[Path | None], durs: list[float], out: Path) -> None:
    if not all(audio):
        shutil.copyfile(silent, out)
        return
    args, filters = ["-i", str(silent)], []
    for a in audio:
        args += ["-i", str(a)]
    for i, d in enumerate(durs):
        filters.append(f"[{i + 1}:a]aresample=44100,apad=whole_dur={d:.2f}[a{i}]")
    filters.append("".join(f"[a{i}]" for i in range(len(durs))) + f"concat=n={len(durs)}:v=0:a=1[aout]")
    run_ffmpeg([*args, "-filter_complex", ";".join(filters), "-map", "0:v", "-map", "[aout]", "-c:v", "copy",
                "-c:a", "aac", "-b:a", "160k", "-t", f"{sum(durs):.2f}", "-movflags", "+faststart", str(out)])


def render_motion_video(content: dict, details: ProjectDetails, accent: str, *, voice: bool = True,
                        out_dir: Path | None = None, progress: Callable[[float, str], None] | None = None) -> Path:
    """Build the HyperFrames composition, render it, add the voiceover. Returns the MP4 path."""
    note = progress or (lambda f, m: None)
    missing = missing_tool()
    if missing:
        raise VideoError(f"Rich animation needs {missing}. Install it, restart the app and try again.")
    npx = _npx()
    scenes = build_scenes(content, details)
    out = _out_path(details, out_dir)
    with tempfile.TemporaryDirectory(prefix="motion-") as tmp:
        work = Path(tmp)
        note(0.05, "Recording the voiceover...")
        audio = make_voiceovers(scenes, work) if voice else [None] * len(scenes)
        durs = _durations(scenes, audio, floor=4.0)
        folder = work / "project"
        folder.mkdir()
        note(0.15, "Designing the animation...")
        build_project(folder, scenes, durs, details, accent)
        silent = work / "silent.mp4"
        note(0.25, "Rendering with HyperFrames (the first run downloads it)...")
        env = {**os.environ, "PATH": _tool_path(), "HYPERFRAMES_NO_TELEMETRY": "1", "DO_NOT_TRACK": "1"}
        try:
            proc = subprocess.run([npx, "--yes", CLI, "render", str(folder), "-o", str(silent), "--quality", "looks",
                                   "--fps", str(FPS)], capture_output=True, text=True, env=env, timeout=RENDER_TIMEOUT)
        except subprocess.TimeoutExpired:
            raise VideoError("The HyperFrames render took too long and was stopped. Try again.")
        if proc.returncode != 0 or not silent.exists():
            tail = [l for l in (proc.stderr + proc.stdout).strip().splitlines() if l.strip()][-1:] or ["unknown error"]
            raise VideoError(f"HyperFrames could not render the video: {tail[0][:200]}")
        note(0.9, "Adding the voiceover...")
        _mux_audio(silent, audio, durs, out)
    note(1.0, "Done")
    return out
