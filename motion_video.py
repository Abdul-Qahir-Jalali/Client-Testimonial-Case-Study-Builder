def _words(text: str) -> str:
    return " ".join(f'<span class="w">{_E(w)}</span>' for w in str(text).split())


def _counting(value: str) -> str:
    """Wrap each number in a span the timeline counts up. For 'A -> B' the first number stays and B counts from A."""
    value = _arrows(value)
    nums = list(_NUM.finditer(value))
    arrow = "\u2192" in value and len(nums) >= 2
    out, last = [], 0
    for i, m in enumerate(nums):
        out.append(_E(value[last:m.start()]))
        to = float(m.group().replace(",", ""))
        dec = len(m.group().split(".")[1]) if "." in m.group() else 0
        if arrow and i == 0:
            frm = to
        elif arrow and i == 1:
            frm = float(nums[0].group().replace(",", ""))
        else:
            frm = 0.0
        out.append(f'<span class="cu" data-from="{frm}" data-to="{to}" data-dec="{dec}" '
                   f'data-comma="{"1" if "," in m.group() else "0"}">{_E(m.group())}</span>')
        last = m.end()
    out.append(_E(value[last:]))
    return "".join(out)


def _size(text: str, tiers: list[tuple[int, int]], smallest: int) -> int:
    for limit, px in tiers:
        if len(text) <= limit:
            return px
    return smallest


def _scene_html(i: int, s: Scene, agency: str, start: float, dur: float) -> str:
    d = s.data
    strip = (f'<div class="brand">{LOGO.format(n=f"b{i}")}<span>{_E(agency)}</span></div>' if s.kind != "cta" else "")
    if s.kind == "hook":
        big = (f'<div class="big" id="big{i}">{_counting(d["big"])}</div><div class="lab" id="lab{i}">{_E(d["label"])}</div>'
               if d["big"] else "")
        title_px = 56 if d["big"] else _size(d["title"], [(60, 104), (110, 88)], 72)
        body = (f'<div class="pill" id="pill{i}">Case study &middot; {_E(d["client"])}</div>{big}'
                f'<div class="ttl" id="ttl{i}" style="font-size:{title_px}px">{_words(d["title"])}</div>')
    elif s.kind == "challenge":
        px = _size(d["text"], [(70, 84), (120, 74)], 64)
        body = (f'<div class="pill" id="pill{i}">The challenge</div>'
                f'<div class="ttl" id="ttl{i}" style="font-size:{px}px">{_words(d["text"])}</div>')
    elif s.kind == "results":
        rows = "".join(
            f'<div class="row" id="row{i}_{k}"><div class="rv">{_counting(r["value"]) if r["value"] else ""}</div>'
            f'<div class="rl">{_E(r["label"])}</div><div class="bar"><i></i></div></div>' for k, r in enumerate(d["rows"]))
        body = f'<div class="pill" id="pill{i}">The results</div><div class="rows">{rows}</div>'
    elif s.kind == "quote":
        px = _size(d["text"], [(80, 76), (140, 64)], 52)
        body = (f'<div class="qm" id="qm{i}">&ldquo;</div><div class="ttl q" id="ttl{i}" style="font-size:{px}px">'
                f'{_words(d["text"])}</div><div class="who" id="who{i}">{_E(d["who"])}</div>')
    else:
        big_logo = LOGO.format(n=f"c{i}").replace('class="logo"', f'class="logo big-logo" id="logo{i}"')
        body = (f'<div class="ring" id="ring{i}"></div>{big_logo}'
                f'<div class="cta1" id="cta1_{i}">Want results like this?</div>'
                f'<div class="cta2" id="cta2_{i}">{_E(d["agency"])}</div><div class="cta3" id="cta3_{i}">Let&rsquo;s talk</div>')
    return (f'<section id="s{i}" class="clip scene" data-start="{max(0.0, start - (OVERLAP if i else 0)):.2f}" '
            f'data-duration="{dur + (OVERLAP if i else 0):.2f}" data-track-index="{i}"><div class="stack {s.kind}">{body}</div>{strip}</section>')


