def _timeline_js(scenes: list[Scene], starts: list[float], durs: list[float], total: float) -> str:
    j = []
    a = j.append
    a("window.__timelines = window.__timelines || {};")
    a("const tl = gsap.timeline({ paused: true });")
    a("const rise=(s,t,y=60,d=.6)=>tl.fromTo(s,{opacity:0,y},{opacity:1,y:0,duration:d,ease:'power3.out'},t);")
    a("const words=(s,t,span)=>tl.fromTo(s+' .w',{opacity:0,y:34,filter:'blur(10px)'},"
      "{opacity:1,y:0,filter:'blur(0px)',duration:.5,ease:'power3.out',stagger:{amount:span}},t);")
    a("const fmt=(v,dec,comma)=>comma?Number(v).toLocaleString('en-US',{minimumFractionDigits:dec,maximumFractionDigits:dec}):Number(v).toFixed(dec);")
    a("const count=(sel,t,dur)=>document.querySelectorAll(sel+' .cu').forEach((el,k)=>{const f=+el.dataset.from,to=+el.dataset.to,"
      "dec=+el.dataset.dec,c=el.dataset.comma==='1',o={p:0};const draw=()=>{el.textContent=fmt(f+(to-f)*o.p,dec,c)};draw();"
      "if(f!==to)tl.to(o,{p:1,duration:dur,ease:'power2.out',onUpdate:draw},t+k*.15);});")
    a(f"tl.fromTo('#bar',{{scaleX:0}},{{scaleX:1,duration:{total:.2f},ease:'none'}},0);")
    a(f"tl.to('.o1',{{x:260,y:520,duration:{total:.2f},ease:'none'}},0);")
    a(f"tl.to('.o2',{{x:-300,y:-420,duration:{total:.2f},ease:'none'}},0);")
    a(f"tl.to('.o3',{{x:300,y:-640,duration:{total:.2f},ease:'none'}},0);")
    for i, (s, t0, d) in enumerate(zip(scenes, starts, durs)):
        sid = f"#s{i}"
        if i:   # blurred, scaling crossfade with the previous scene
            a(f"tl.fromTo('{sid}',{{opacity:0,filter:'blur(26px)',scale:1.07}},{{opacity:1,filter:'blur(0px)',scale:1,duration:{OVERLAP},ease:'power2.out'}},{t0 - OVERLAP:.2f});")
            a(f"tl.to('#s{i - 1}',{{opacity:0,filter:'blur(18px)',scale:.96,duration:{OVERLAP},ease:'power2.in'}},{t0 - OVERLAP:.2f});")
        else:
            a(f"gsap.set('{sid}',{{opacity:1}});")
        b = t0 + 0.15
        if s.kind == "hook":
            a(f"rise('#pill{i}',{b:.2f},40,.5);")
            if s.data["big"]:
                a(f"tl.fromTo('#big{i}',{{opacity:0,scale:.7,y:40}},{{opacity:1,scale:1,y:0,duration:.8,ease:'back.out(1.5)'}},{b + .15:.2f});")
                a(f"count('#big{i}',{b + .2:.2f},1.4);")
                a(f"rise('#lab{i}',{b + .8:.2f},40,.55);")
                a(f"words('#ttl{i}',{b + 1.2:.2f},{min(1.4, d * .3):.2f});")
            else:
                a(f"words('#ttl{i}',{b + .3:.2f},{min(1.6, d * .4):.2f});")
        elif s.kind == "challenge":
            a(f"rise('#pill{i}',{b:.2f},40,.5);")
            a(f"words('#ttl{i}',{b + .45:.2f},{min(d * .55, 2.6):.2f});")
        elif s.kind == "results":
            a(f"rise('#pill{i}',{b:.2f},40,.5);")
            for k, row in enumerate(s.data["rows"]):
                t = b + .5 + k * .55
                a(f"rise('#row{i}_{k}',{t:.2f},60,.55);")
                a(f"count('#row{i}_{k}',{t + .1:.2f},1.3);")
                a(f"tl.fromTo('#row{i}_{k} .bar i',{{scaleX:0}},{{scaleX:1,duration:1.2,ease:'power3.out'}},{t + .2:.2f});")
        elif s.kind == "quote":
            a(f"tl.fromTo('#qm{i}',{{opacity:0,scale:.3,rotation:-12}},{{opacity:1,scale:1,rotation:0,duration:.7,ease:'back.out(1.8)'}},{b:.2f});")
            a(f"words('#ttl{i}',{b + .35:.2f},{min(d * .55, 3.2):.2f});")
            a(f"rise('#who{i}',{t0 + d * .72:.2f},30,.55);")
        else:
            a(f"tl.fromTo('#logo{i} .hex',{{strokeDasharray:1,strokeDashoffset:1}},{{strokeDashoffset:0,duration:.9,ease:'power2.inOut'}},{b:.2f});")
            a(f"tl.fromTo('#logo{i}',{{opacity:0,scale:.6,rotation:-10}},{{opacity:1,scale:1,rotation:0,duration:.8,ease:'back.out(1.6)'}},{b:.2f});")
            a(f"tl.fromTo('#ring{i}',{{opacity:.7,scale:.6}},{{opacity:0,scale:1.6,duration:1.2,ease:'power2.out'}},{b + .5:.2f});")
            a(f"rise('#cta1_{i}',{b + .6:.2f},50,.6);")
            a(f"rise('#cta2_{i}',{b + 1.0:.2f},40,.55);")
            a(f"rise('#cta3_{i}',{b + 1.3:.2f},30,.5);")
    a(f"tl.to('#s{len(scenes) - 1}',{{opacity:0,duration:.4,ease:'none'}},{total - .4:.2f});")
    a("window.__timelines['main'] = tl;")
    a("tl.seek(0);")
    return "\n".join(j)


def build_project(folder: Path, scenes: list[Scene], durs: list[float], details: ProjectDetails, accent_hex: str) -> None:
    accent = hex_rgb(accent_hex)
    hexc = lambda c: "#%02x%02x%02x" % tuple(c)
    css = CSS % {"a": hexc(accent), "soft": hexc(mix(accent, (255, 255, 255), .55)),
                 "mid": hexc(mix((11, 16, 32), accent, .30)), "bot": hexc(mix((11, 16, 32), accent, .52))}
    starts = [sum(durs[:i]) for i in range(len(durs))]
    total = sum(durs)
    body = "\n".join(_scene_html(i, s, details.agency_name, st, d) for i, (s, st, d) in enumerate(zip(scenes, starts, durs)))
    page = f"""<!doctype html>
<html lang="en" data-resolution="portrait">
<head><meta charset="UTF-8"><meta name="viewport" content="width=1080, height=1920">
<script src="{_gsap_tag()}"></script>
<style>{css}</style></head>
<body>
<div id="root" data-composition-id="main" data-start="0" data-duration="{total:.2f}" data-width="{W}" data-height="{H}" data-fps="{FPS}">
<div id="bg" class="clip" data-start="0" data-duration="{total:.2f}" data-track-index="20"><div class="orb o1"></div><div class="orb o2"></div><div class="orb o3"></div></div>
<div id="bar" class="clip" data-start="0" data-duration="{total:.2f}" data-track-index="21"></div>
{body}
</div>
<script>
{_timeline_js(scenes, starts, durs, total)}
</script>
</body></html>"""
    (folder / "index.html").write_text(page, encoding="utf-8")
    (folder / "meta.json").write_text(json.dumps({"id": "reel", "name": "reel"}), encoding="utf-8")
    (folder / "hyperframes.json").write_text(json.dumps({
        "$schema": "https://hyperframes.heygen.com/schema/hyperframes.json",
        "registry": "https://raw.githubusercontent.com/heygen-com/hyperframes/main/registry",
        "paths": {"blocks": "compositions", "components": "compositions/components", "assets": "assets"},
        "media": {"autoProxy": True}}), encoding="utf-8")
    (folder / "package.json").write_text(json.dumps({"name": "reel", "private": True, "type": "module"}), encoding="utf-8")
    if _gsap_tag() == "assets/gsap.min.js":
        (folder / "assets").mkdir(exist_ok=True)
        shutil.copyfile(GSAP_CACHE, folder / "assets" / "gsap.min.js")


