NUM_SPLIT = re.compile(r"^(.*?)(\d[\d,]*(?:\.\d+)?)(.*)$")
CHALLENGE_STAT = re.compile(r"(~?\d[\d,.]*\s?%?)\s+((?:[a-z][\w'-]*\s+){0,3}[a-z][\w'-]*)", re.IGNORECASE)
STOP_TAIL = {"and", "or", "the", "a", "of", "to", "in", "on", "for", "with", "was", "were", "is", "are"}


def _icon_for(text: str) -> str:
    low = f" {text.lower()} "
    for words, icon in STEP_KEYWORDS:
        if any(w in low for w in words):
            return icon
    return "spark"


def _counter(value: str) -> dict:
    """'~4 hours' -> {'pre':'~','num':4,'dec':0,'suf':' hours','comma':False}; non-numeric -> text only."""
    value = _compact(value)
    m = NUM_SPLIT.match(value)
    if not m:
        return {"text": value}
    raw = m.group(2)
    return {"pre": m.group(1), "num": float(raw.replace(",", "")), "dec": len(raw.split(".")[1]) if "." in raw else 0,
            "suf": m.group(3), "comma": "," in raw, "text": value}


def _sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"'])", (text or "").strip())
    return [p.strip() for p in parts if p.strip()]


def _challenge_stats(challenge: str, metrics: list[dict]) -> list[dict]:
    """Numbers that describe the 'before' world: metric 'before' values, then figures found in the challenge text."""
    stats, seen = [], set()
    for m in metrics:
        if m["before"]:
            c = _counter(m["before"])
            stats.append({**c, "label": m["label"]})
            seen.add(c.get("num"))
    for m in CHALLENGE_STAT.finditer(challenge or ""):
        c = _counter(m.group(1).strip())
        if c.get("num") is None or c["num"] in seen:
            continue
        words = m.group(2).split()
        while words and words[-1].lower() in STOP_TAIL:
            words.pop()
        if not words:
            continue
        seen.add(c["num"])
        stats.append({**c, "label": " ".join(words)})
    return stats[:3]


def _quote(q: dict | None, company: str = "") -> dict | None:
    if not q:
        return None
    role = ", ".join(x for x in [q.get("speaker_role"), company] if x)
    return {"text": q.get("text", ""), "name": q.get("speaker_name", ""), "role": role,
            "initials": _initials(q.get("speaker_name"))}


def build_story_data(content: dict, details) -> dict:
    cs = content.get("case_study", {})
    quotes = content.get("testimonials", [])
    metrics = [parse_metric(m) for m in cs.get("key_metrics", []) if m.get("value")]
    client = details.client_name or "Our client"

    opening = _pick_featured_quote(quotes, details.contact_name)
    closing = _pick_closing_quote(quotes, [opening])
    voices = [q for q in quotes if q is not opening and q is not closing][:3]

    challenge = _sentences(cs.get("challenge", ""))
    return {
        "client": client,
        "agency": details.agency_name or "",
        "title": cs.get("title", ""),
        "summary": cs.get("summary", ""),
        "facts": [{"k": k, "v": v} for k, v in [("Industry", details.industry), ("Service", details.service),
                                               ("Timeline", details.timeline)] if v],
        "problem": {"lead": challenge[0] if challenge else "", "points": challenge[1:4],
                    "stats": _challenge_stats(cs.get("challenge", ""), metrics)},
        "steps": [{"text": s, "icon": _icon_for(s)} for s in cs.get("solution", [])][:6],
        "transforms": [{"label": m["label"], "before": _counter(m["before"]), "after": _counter(m["after"]),
                        "bars": m["bars"]} for m in metrics if m["before"]][:3],
        "metrics": [{"label": m["label"], **_counter(m["after"] if m["before"] else m["value"])} for m in metrics][:4],
        "results": cs.get("results", [])[:5],
        "opening": _quote(opening, client),
        "voices": [_quote(q) for q in voices],
        "closing": _quote(closing, client),
    }


